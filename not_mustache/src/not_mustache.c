static mustache_param* get_pstack_child_by_index(parent_stack *pstack, uint32_t dotcount, int32_t idx)
{
    mustache_param* child;
    uint32_t max_children;

    // go up
    parent_stack_block* b = ((parent_stack_block*)pstack->buf.u)+pstack->count-1-dotcount;
    mustache_param* parent_param = b->param;
    child = mustache_parameter_get_child_list(parent_param, &max_children);

    if (idx<0) {
        idx=max_children+idx;
    }

    uint32_t i = 0;
    while (child && i < max_children)
    {
        if (i==idx) {
            return child;
        }
        ++i;
        child = child->pNext;
    }
    return NULL;
    
}

static mustache_param* get_pstack_child_by_name(parent_stack *pstack,  uint32_t dotcount, const char* name, const char* name_end)
{
    mustache_param* child;
    uint32_t max_children;

    // go up
    parent_stack_block* b = ((parent_stack_block*)pstack->buf.u)+pstack->count-dotcount;
    mustache_param* parent_param = b->param;
    child = mustache_parameter_get_child_list(parent_param, &max_children);
    uint32_t i = 0;
    while (child && i < max_children)
    {
        size_t target_name_len  =name_end-name;
        if (child->name.len == target_name_len && strneql(child->name.u, name, target_name_len)) {
            return child;
        }
        ++i;
        child = child->pNext;
    }
    return NULL;
}


static mustache_param* get_root_child_by_name(mustache_param* root, const char* name, const char* name_end) {
    mustache_param* child = root;
    uint32_t max_children;

    while (child)
    {
        size_t target_name_len  =name_end-name;

        if (child->name.len == target_name_len && strneql(child->name.u, name, target_name_len)) {
            return child;
        }
        child = child->pNext;
    }
    return NULL;
}

