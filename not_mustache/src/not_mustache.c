// https://www.json.org/json-en.html
// since mustache doesn't require support for any charset other than ASCII,
// there is a slight conflict with the JSON spec, which mandates UTF-8 encoding

// returns the actual name length, factoring in any escape characters
// 
// if the buffer exists, this will also write the string!
// thus, only use this for strings and key names
//
// note that send-sfirst DOES not give the evaluated length - it is a seperate property.
// however, if ji->cur isn't NULL, send-sfirst is the same as evaluated_len.
static const char* grab_JSON_string(mustache_json_info* ji, const char* sfirst, const char** send, const char**input_end, size_t* evaluated_len, const char* src_end)
{
    // 1 past opening "
    sfirst++;

    size_t esc_char_count=0;


    size_t name_len = 0;
    const char* vend = sfirst;
    while (vend < src_end)
    {
        const char c = *vend;
        if (c == '\\' && vend < src_end-1) {
            if (esc_char_count==SIZE_MAX) {
                return NULL;
            }
            esc_char_count++;
        }
        if (*(vend-1)!='\\'&&c=='"') {
            if (input_end) {
                *input_end=vend;
            }
            break;
        }
        vend++;
    }

    if (esc_char_count) {
        name_len=vend-sfirst-esc_char_count;
        
        if (SIZE_MAX - ji->buffer_size < name_len) {
            *send=NULL;
            return NULL;
        }
        ji->buffer_size += name_len;

    } else {
        name_len=vend-sfirst;

        if (ji->copy_strings) {
            if (SIZE_MAX - ji->buffer_size < name_len) {
                *send=NULL;
                return NULL;
            }
            ji->buffer_size += name_len;
        }
    }


    if (ji->cur) 
    {
        const char* str = ji->cur;

        // write string
        if (esc_char_count) {
            while (sfirst < *send)
            {
                char c = *sfirst;
                if (c=='\\' && sfirst < (*send)-1) {
                    sfirst++;
                    c=*sfirst;
                    if (c=='n') {
                        *ji->cur++ = c;
                    }
                    else if (c=='r') {
                        *ji->cur++ = '\r';
                    }
                    else if (c=='b') {
                        *ji->cur++ = '\b';
                    }
                    else if (c=='f') {
                        *ji->cur++ = '\f';
                    }
                    else if (c=='t') {
                        *ji->cur++ = '\t';
                    }
                    else if (c=='/') {
                        *ji->cur++ = c;
                    } else if (c=='u') {
                        char warn[256];
                        snprintf(warn,sizeof(warn),"This templating engine does not support unicode characters, the '/u' escape code within JSON will be ignored.");
                        ji->parser->warn_callback(ji->parser,warn,sfirst,*send);
                    }
                } else {
                    *ji->cur++ = c;
                }
            
                sfirst++;
            }
        }
        else if (ji->copy_strings) {
            memcpy(ji->cur, sfirst, name_len);
            ji->cur += name_len;
        }

        *evaluated_len=name_len;

        *send=ji->cur;
        return str;
    }

    *evaluated_len=name_len;
    *send=vend;
    return sfirst;
}

