mustache_param* mustache_param_get_child_at_index(mustache_param* p, uint32_t index)
{
    uint32_t max_c;
    if (p->type==MUSTACHE_PARAM_OBJECT) {
        mustache_param_object *obj = (mustache_param_object*)p;
        max_c = UINT32_MAX;
        p=obj->pMembers;
    } else if (p->type==MUSTACHE_PARAM_LIST) {
        mustache_param_list *list = (mustache_param_list*)p;
        max_c = list->valueCount;
        p=list->pValues;
    } else {
        return NULL;
    }


    uint32_t i=0;
    while (p && i < max_c)
    {
        if (i==index) {
            return p;
        }
        i++;
        p=p->pNext;
    }
    
    return NULL;
}



uint8_t mustache_parse_file(mustache_parser* parser, mustache_slice parentStackBuffer, mustache_const_slice filename, mustache_structure* structChain, mustache_param* params, mustache_slice sourceBuffer, mustache_slice parseBuffer, void* parseCallbackUdata, mustache_parse_callback parseCallback)
{
#ifndef NDEBUG
    if (filename.len > 2048) {
        assert(00 && "mustache_parse_file: SUCH A LARGE FILENAME MAY RESULT IN PROGRAM INSTABILITY!");
    }
#endif
    /* tragically fopen requires a null terminated string, and there is no workaround even for an all-around */
    /* system specific design, it's possible on Windows but not on Linux to my knowledge :( */
    uint8_t* filenameNT = alloca(filename.len + 1);
    memcpy(filenameNT, filename.u, filename.len);
    filenameNT[filename.len] = 0;

    FILE* fptr;
    fptr = fopen(filenameNT, "rb");
    if (!fptr) {
        return MUSTACHE_ERR_FILE_OPEN;
    }

    /* parse in chunks */
    mustache_stream stream = {
        .udata = fptr,
        .readCallback = fread_callback,
        .seekCallback = fseek_callback,
    };

    uint8_t err = mustache_parse_stream(parser, parentStackBuffer, &stream, structChain, params, sourceBuffer, parseBuffer, parseCallbackUdata, parseCallback);
    fclose(fptr);
    return err;
}

uint8_t mustache_parse_stream(mustache_parser* parser, mustache_slice parentStackBuffer, mustache_stream* stream, mustache_structure* structChain,
    mustache_param* params, mustache_slice inputBuffer, mustache_slice outputBuffer, void* parseCallbackUdata, mustache_parse_callback parseCallback)
{
    if (!parser->err_callback) {
        parser->err_callback = mustache_dummy_err_callback;
    }
    if (!parser->warn_callback) {
        parser->warn_callback = mustache_dummy_err_callback;
    }

    const uint8_t* inputHead = inputBuffer.u;
    const uint8_t* inputBeg = inputBuffer.u;

    const uint8_t* mustacheOpen = NULL;
    const uint8_t* mustacheClose = inputBuffer.u;


    // reset stream position
    (void)stream->seekCallback(stream->udata, 0, MUSTACHE_SEEK_SET);

    size_t streamLen = stream->seekCallback(stream->udata, 0, MUSTACHE_SEEK_LEN);
    if (streamLen==0) {return MUSTACHE_SUCCESS;}
    size_t read_len=0; // total number of bytes read


    structure_root* structureRoot = (structure_root*)structChain;
    structureRoot->type = STRUCTURE_TYPE_ROOT;
    structure_root* lastRoot = structureRoot;

    int i = 0;
    while (read_len<streamLen)
    {
        size_t dstlen = (streamLen-read_len < inputBuffer.len) ? (streamLen-read_len) : inputBuffer.len;
        size_t readBytes = stream->readCallback(stream->udata, inputBuffer.u, dstlen);
        if (readBytes > streamLen) {
            return MUSTACHE_ERR_NO_SPACE;
        }
        if (readBytes==0) {
            printf("BREAK");
            break;
        }
        
        read_len+=readBytes;

        const uint8_t* inputEnd = inputBuffer.u + readBytes;

        parent_stack parentStack = {
            .buf =  parentStackBuffer,
            .count = 0,
            .MAX_COUNT = parentStackBuffer.len / (sizeof(parent_stack_block))
        };


        structure* schain=NULL;
        MUSTACHE_RES err;
        if (!lastRoot->pNext) {
            err = source_to_structured(parser, params, &parentStack, (structure*)lastRoot, inputBuffer.u, inputHead, inputEnd, &schain);
            if (err) {
                return err;
            }
            
            err = structured_init_dot_params(parser, &parentStack, params, schain, lastRoot);
            if (err) {
                return err;
            }
            

            mustache_dbg_print_structure_chain((mustache_structure*)schain, 0);

            // alloc another root
            structure_root* root = parser->alloc(parser,sizeof(structure_root));
            if (!root) {
                return MUSTACHE_ERR_ALLOC;
            }
            root->type = STRUCTURE_TYPE_ROOT;
            lastRoot->pNextRoot = (structure*)root;
        }

        char*outputHead;
        err = write_structured(parser, stream, &outputHead, outputBuffer.u, outputBuffer.u+outputBuffer.len, inputBuffer.u, inputBuffer.u + readBytes, schain);

        // err = write_structured(
        //     outputBuffer, &outputHead,
        //     (mustache_const_slice){ inputBuffer.u,inputBuffer.len },
        //     inputBuffer.u + readBytes,
        //     (structure*)lastRoot, params, &parentStack,
        //     parser
        // );

        if (err) {
            return err;
        }

        mustache_slice parsedSlice = {
            .u = outputBuffer.u,
            .len = outputHead - (char*)outputBuffer.u,
        };


        parseCallback(parser, parseCallbackUdata, parsedSlice);

        lastRoot = (structure_root*)lastRoot->pNextRoot;
        ++i;
    }



    return MUSTACHE_SUCCESS;
}

















